// Emits supabase/migrations/0004_permissions_seed.sql from permissionMatrix(),
// the union of every feature manifest. check:contract renders it in memory and
// fails when the file on disk differs.
// Usage: pnpm tsx scripts/gen-permissions-sql.ts

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { permissionMatrix, type Permission, type PermissionDef } from '@/core/permissions';
import type { Role } from '@/core/vocab';

export const PERMISSIONS_SQL_PATH = join(import.meta.dirname, '..', 'supabase', 'migrations', '0004_permissions_seed.sql');

const ROLE_ORDER: ReadonlyArray<Role> = ['admin', 'leader', 'dept_leader', 'user'];

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function renderPermissionsSql(matrix: ReadonlyMap<Permission, PermissionDef>): string {
  const rows = [...matrix].flatMap(([perm, def]) =>
    ROLE_ORDER.map(
      (role) => `  (${sqlString(perm)}, ${sqlString(role)}, ${sqlString(def.grants[role])}, ${sqlString(def.scope)}, ${def.requiresAal2 ? 'true' : 'false'})`,
    ),
  );
  const keys = [...matrix.keys()].map(sqlString).join(', ');
  return `-- 0004_permissions_seed.sql
-- GENERATED by scripts/gen-permissions-sql.ts from permissionMatrix() (every
-- feature manifest). Do not edit by hand: \`npm run check:contract\` regenerates
-- it in memory and fails when this file differs. Converges the table to the
-- matrix exactly (upsert + delete of keys no manifest declares).

insert into public.sce_tcsk_role_permissions (permission, role, grant_level, scope, requires_aal2) values
${rows.join(',\n')}
on conflict (permission, role) do update set
  grant_level = excluded.grant_level, scope = excluded.scope, requires_aal2 = excluded.requires_aal2;

delete from public.sce_tcsk_role_permissions
 where permission not in (${keys});
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(PERMISSIONS_SQL_PATH, renderPermissionsSql(permissionMatrix()));
  console.log(`wrote ${PERMISSIONS_SQL_PATH}`);
}
