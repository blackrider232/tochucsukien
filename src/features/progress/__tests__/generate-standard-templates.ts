// Regenerates domain/standard-templates.ts from the legacy generator.
// Run: pnpm tsx src/features/progress/__tests__/generate-standard-templates.ts
// standard-templates.test.ts proves the table still reproduces the legacy output.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { runLegacyGenerator, type LegacyGroup, type LegacyStep } from './legacy-generator';

const LEAD = '__LEAD__';
const T0 = '2026-12-15';
const GROUP_KEYS = ['g1', 'g2', 'g3', 'g4', 'g5', 'g6', 'dday'] as const;

// Numbers the legacy text hard-coded although they are system settings (m2 BUG-07).
const PLACEHOLDERS: ReadonlyArray<[RegExp, string]> = [
  [/130%/g, '{guestQuotaPercent}%'],
  [/120%/g, '{badgeQuotaPercent}%'],
  [/T - 10/g, 'T - {dailyReportThresholdDays}'],
  [/Hội chợ 10 ngày/g, 'Hội chợ {dailyReportThresholdDays} ngày'],
  [/2 tiếng/g, '{fieldPresenceHours} tiếng'],
  [/T0 - 2h/g, 'T0 - {fieldPresenceHours}h'],
];
const placeholders = (s: string) => PLACEHOLDERS.reduce((acc, [re, to]) => acc.replace(re, to), s);

const lit = (v: unknown) => JSON.stringify(v);
function byType(hn: unknown, hc: unknown, render: (v: unknown) => string = lit): string {
  return lit(hn) === lit(hc) ? render(hn) : `{ hoi_nghi: ${render(hn)}, hoi_cho: ${render(hc)} }`;
}
const text = (v: unknown) => lit(placeholders(v as string));
const subTasks = (v: unknown) => `[${(v as LegacyStep['subTasks']).map((s) => text(s.name)).join(', ')}]`;

function leadText(withLead: string, withoutLead: string): string {
  return withLead === LEAD ? `{ lead: ${lit(withoutLead)} }` : lit(withLead);
}

function stepSource(key: string, hn: LegacyStep | undefined, hc: LegacyStep | undefined, hnBare: LegacyStep | undefined, hcBare: LegacyStep | undefined): string {
  const a = hn ?? hc!;
  const b = hc ?? hn!;
  const bare = hnBare ?? hcBare!;
  const offset = key === 'step_6a' ? `'dailyReportThresholdDays'` : byType(a.offsetDays, b.offsetDays);
  const lines = [
    `key: ${lit(key)}`,
    `name: ${byType(a.name, b.name, text)}`,
    `requirement: ${byType(a.requirement, b.requirement, text)}`,
    `offsetDays: ${offset}`,
    `dayType: ${byType(a.dayType, b.dayType)}`,
    `targetPhase: ${byType(a.targetPhase, b.targetPhase)}`,
    `assignee: ${leadText(a.assignee, bare.assignee)}`,
    `templateKey: ${byType(a.templateKey, b.templateKey)}`,
    `subTasks: ${byType(a.subTasks, b.subTasks, subTasks)}`,
    ...(hn ? [] : [`onlyFor: 'hoi_cho'`]),
  ];
  return `      { ${lines.join(', ')} },`;
}

function groupSource(i: number, hn: LegacyGroup, hc: LegacyGroup, hnBare: LegacyGroup, hcBare: LegacyGroup): string {
  const keys = [...new Set([...hc.steps.map((s) => s.id), ...hn.steps.map((s) => s.id)])];
  const ordered = hc.steps.map((s) => s.id).concat(keys.filter((k) => !hc.steps.some((s) => s.id === k)));
  const find = (g: LegacyGroup, k: string) => g.steps.find((s) => s.id === k);
  return [
    '  {',
    `    key: ${lit(GROUP_KEYS[i])}, phase: ${lit(hn.phase)}, name: ${byType(hn.name, hc.name)},`,
    `    leadPerson: ${leadText(hn.leadPerson, hnBare.leadPerson)}, note: ${text(hn.note)},`,
    '    steps: [',
    ...ordered.map((k) => stepSource(k, find(hn, k), find(hc, k), find(hnBare, k), find(hcBare, k))),
    '    ],',
    '  },',
  ].join('\n');
}

const hn = runLegacyGenerator('hoi_nghi', T0, LEAD);
const hc = runLegacyGenerator('hoi_cho', T0, LEAD);
const hnBare = runLegacyGenerator('hoi_nghi', T0, '');
const hcBare = runLegacyGenerator('hoi_cho', T0, '');

const out = `// GENERATED by __tests__/generate-standard-templates.ts from legacy/index.html
// (generateStandardEventTemplate). Do not edit by hand: regenerate, and
// standard-templates.test.ts checks the table against the legacy generator.

import type { TemplateGroup } from './template-types';

export const STANDARD_TEMPLATE: ReadonlyArray<TemplateGroup> = [
${hn.map((g, i) => groupSource(i, g, hc[i]!, hnBare[i]!, hcBare[i]!)).join('\n')}
];
`;
writeFileSync(join(import.meta.dirname, '..', 'domain', 'standard-templates.ts'), out);
console.log(`wrote standard-templates.ts: ${hn.length} groups, HN ${hn.flatMap((g) => g.steps).length} steps, HC ${hc.flatMap((g) => g.steps).length} steps`);
