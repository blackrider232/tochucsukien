// Regenerates domain/builtins/*.ts from legacy/index.html plus LEGACY_FIXES.
// Run: pnpm tsx src/features/templates/__tests__/generate-builtin-templates.ts
// builtin-templates.test.ts fails when the shipped data drifts from this output.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fixedLegacyTemplates, type LegacyTemplate } from './legacy-templates';

const OUT = join(import.meta.dirname, '..', 'domain', 'builtins');
const FILES: ReadonlyArray<{ group: string; file: string; name: string; label: string }> = [
  { group: 'cap_ubnd', file: 'ubnd.ts', name: 'UBND_TEMPLATES', label: 'Cấp UBND Thành phố Hà Nội' },
  { group: 'cap_stc', file: 'stc.ts', name: 'STC_TEMPLATES', label: 'Cấp Sở Tài chính' },
  { group: 'cap_trungtam', file: 'trungtam.ts', name: 'TRUNGTAM_TEMPLATES', label: 'Cấp Trung tâm (SCE)' },
];

const HEX = /#[0-9a-fA-F]{3,8}\b/;
const DISABLE_HEX = `/* eslint-disable no-restricted-syntax --
   Document content: the inline Word/print styles carry colours that are not UI colours. */
`;

const lit = (s: string) => JSON.stringify(s);
const tpl = (s: string) => `\`${s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``;

function entry(t: LegacyTemplate): string {
  return [
    '  {',
    `    id: ${lit(t.id)}, level: ${lit(t.group)}, code: ${lit(t.code)}, kind: ${lit(t.type)},`,
    `    title: ${lit(t.title)},`,
    `    description: ${lit(t.description)},`,
    `    content: ${tpl(t.content)},`,
    '  },',
  ].join('\n');
}

const all = fixedLegacyTemplates();

writeFileSync(join(OUT, 'ids.ts'), `// GENERATED by __tests__/generate-builtin-templates.ts. Do not edit by hand.

export const BUILTIN_IDS = [
${all.map((t) => `  ${lit(t.id)},`).join('\n')}
] as const;
export type BuiltinId = (typeof BUILTIN_IDS)[number];
`);

for (const { group, file, name, label } of FILES) {
  const rows = all.filter((t) => t.group === group);
  writeFileSync(join(OUT, file), `// GENERATED by __tests__/generate-builtin-templates.ts from legacy/index.html (${label}, ${rows.length} mẫu).
// Do not edit by hand: change LEGACY_FIXES and regenerate. builtin-templates.test.ts diffs this file against legacy.
${rows.some((t) => HEX.test(t.content)) ? DISABLE_HEX : ''}
import type { BuiltinTemplate } from './types';

export const ${name}: ReadonlyArray<BuiltinTemplate> = [
${rows.map(entry).join('\n')}
];
`);
}
console.log(`wrote ${all.length} templates`);
